class Module:
    """Collects one generated module's imports and body."""

    def __init__(self, doc: str) -> None:
        self.doc = doc
        self.types: set[str] = set()
        self.enums: set[str] = set()
        self.body: list[str] = []

    def render(self, base_names: str) -> str:
        imports = []
        if "date" in self.types or "datetime" in self.types:
            used = sorted({"date", "datetime"} & self.types)
            imports.append(f"from datetime import {', '.join(used)}")
        if "Decimal" in self.types:
            imports.append("from decimal import Decimal")
        if "UUID" in self.types:
            imports.append("from uuid import UUID")
        lines = [
            HEADER.format(doc=self.doc),
            *imports,
            "",
            "from pydantic import Field",
            "",
        ]
        lines.append(f"from ajera.schemas.database.base import {base_names}")
        if self.enums:
            lines.append(
                "from ajera.schemas.database.enums import (\n"
                + "".join(f"    {name},\n" for name in sorted(self.enums))
                + ")"
            )
        return "\n".join(lines) + "\n\n" + "\n".join(self.body)


def render_model(
    module: Module,
    *,
    class_name: str,
    doc: str,
    source_args: str,
    columns: list[dict[str, Any]],
    names: dict[str, str],
    enum_for: dict[str, str],
    notes: dict[str, str] | None = None,
) -> None:
    lines = [
        "",
        f"class {class_name}(DatabaseRecord):",
        f'    """{doc}"""',
        "",
        f"    __source__ = Source({source_args})",
        "",
    ]
    for column in columns:
        sql_type = column["type"]
        py_type = PY_TYPES[sql_type]
        module.types.add(py_type)
        blob = sql_type in BLOB_TYPES
        nullable = column["nullable"] or blob

        enum = enum_for.get(column["name"]) if py_type == "int" else None
        arguments = [f'alias="{column["name"]}"']
        extra = {"sql_type": sql_type}
        if enum:
            module.enums.add(enum)
            annotation = f"{enum} | int"
            arguments.append('union_mode="left_to_right"')
        else:
            annotation = py_type
        if SENSITIVE.search(column["name"]):
            arguments.append("repr=False")
            extra["sensitive"] = True
        if notes and column["name"] in notes:
            extra["note"] = notes[column["name"]]
        arguments.append(f"json_schema_extra={python_dict(extra)}")
        if nullable:
            annotation += " | None"
            arguments.insert(0, "None")
        lines.append(
            f"    {names[column['name']]}: {annotation} = Field({', '.join(arguments)})"
        )
    module.body.extend(lines)
    module.body.append("")


def python_dict(values: dict[str, Any]) -> str:
    """A dict literal with double-quoted strings, which may hold any character."""
    items = (
        f"{json.dumps(key)}: {json.dumps(value) if isinstance(value, str) else repr(value)}"
        for key, value in values.items()
    )
    return "{" + ", ".join(items) + "}"


def column_notes(
    name: str,
    source: dict[str, Any],
    repeated_key: str | None = None,
    names: dict[str, str] | None = None,
) -> dict[str, str]:
    """
    Each column's note: the hand-written one, the probe's, then any repeat.

    The probe's sentence is left off a note that says itself how @StartDate
    acts: `glaCurrentYTDBalance` moves with it only on retained earnings, which
    a bare "Changes with @StartDate." would misstate. Where `VARYING` lists
    the columns that differ between rows sharing the repeated key, every
    other amount repeats with the key, and says so.

    Raises:
        SystemExit: A note names a column the source does not have.
    """
    written = NOTES.get(name, {})
    order = [c["name"] for c in source["columns"]]
    columns = set(order)
    unknown = sorted((set(written) | set(VARYING.get(name, ()))) - columns)
    if unknown:
        raise SystemExit(f"notes.py: {name} has no column {', '.join(unknown)}")
    probed: dict[str, bool] = source.get("start_date_columns", {})
    repeats: set[str] = set()
    repeat = ""
    if repeated_key and name in VARYING:
        key = (names or {}).get(repeated_key, repeated_key)
        repeat = (
            f"Repeats on every row of one `{key}`: count it once per key, "
            "not once per row."
        )
        repeats = {
            c["name"]
            for c in source["columns"]
            if c["type"] in AMOUNT_TYPES and c["name"] not in VARYING[name]
        }
    return {
        column: " ".join(
            text
            for text in (
                written.get(column),
                START_DATE[probed[column]]
                if column in probed and "@StartDate" not in written.get(column, "")
                else None,
                repeat if column in repeats else None,
            )
            if text
        )
        for column in sorted(columns, key=order.index)
        if column in written or column in probed or column in repeats
    }


def declaration(parameter: dict[str, Any]) -> str:
    """A parameter's SQL declaration: `smalldatetime`, `varchar(10)`, `decimal(19,2)`."""
    if "length" in parameter:
        length = parameter["length"]
        return f"{parameter['type']}({'max' if length == -1 else length})"
    if "precision" in parameter:
        return f"{parameter['type']}({parameter['precision']},{parameter['scale']})"
    return str(parameter["type"])


def listed(items: list[str], conjunction: str = "and") -> str:
    """Join `a`, `a and b`, or `a, b, and c`."""
    if len(items) < 3:
        return f" {conjunction} ".join(items)
    return f"{', '.join(items[:-1])}, {conjunction} {items[-1]}"


def ignored_caveat(arguments: list[str], fields: list[str], notes: list[str]) -> str:
    """The docstring sentence for a typed method whose function ignores arguments."""
    text = (
        f"The function ignores {listed([f'`{a}`' for a in arguments])}; "
        "pass None, or the call logs a warning."
    )
    if fields:
        unique = [f"`{field}`" for field in dict.fromkeys(fields)]
        text += f" Filter on {' or '.join(unique)} instead."
    return " ".join([text, *dict.fromkeys(notes)])


def conditional_caveat(
    arguments: list[str], conditions: dict[str, tuple[Any, ...]], arg: dict[str, str]
) -> str:
    """The docstring sentence for arguments a function ignores under some codes."""
    held = listed(
        [
            f"`{arg[code]}` "
            + listed(["None" if v is None else str(v) for v in values], "or")
            for code, values in conditions.items()
        ]
    )
    return (
        f"With {held}, the function ignores "
        f"{listed([f'`{a}`' for a in arguments])}: its rows are the same "
        "whatever they hold, and a value passed to them logs a warning."
    )


def source_literal(**values: Any) -> str:
    parts = [f'kind="{values["kind"]}"', f'name="{values["name"]}"']
    if values.get("primary_key"):
        parts.append(f"primary_key={tuple(values['primary_key'])!r}")
    if values.get("foreign_keys"):
        pairs = ", ".join(
            f'"{column}": ("{table}", "{target}")'
            for column, (table, target) in sorted(values["foreign_keys"].items())
        )
        parts.append(f"foreign_keys={{{pairs}}}")
    if values.get("blobs"):
        parts.append(f"blobs={tuple(values['blobs'])!r}")
    if values.get("parameters"):
        parts.append(f"parameters={tuple(values['parameters'])!r}")
    if values.get("parameter_types"):
        parts.append(f"parameter_types={tuple(values['parameter_types'])!r}")
    if values.get("ignored_parameters"):
        parts.append(f"ignored_parameters={tuple(values['ignored_parameters'])!r}")
    for name in ("parameter_filters", "parameter_notes"):
        if values.get(name):
            parts.append(f"{name}={dict(values[name])!r}")
    if values.get("ignored_when"):
        parts.append(f"ignored_when={values['ignored_when']!r}")
    for name in ("current_column", "deleted_column"):
        if values.get(name):
            parts.append(f'{name}="{values[name]}"')
    if values.get("sensitive"):
        parts.append(f"sensitive={tuple(values['sensitive'])!r}")
    if values.get("row_key"):
        parts.append(f"row_key={tuple(values['row_key'])!r}")
    if values.get("repeated_key"):
        parts.append(f'repeated_key="{values["repeated_key"]}"')
    if values.get("note"):
        parts.append(f"note={json.dumps(values['note'])}")
    return ", ".join(parts)


