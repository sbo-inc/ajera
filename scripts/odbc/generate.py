"""
Generate the database models and function reads from the catalog snapshot.

Inputs are `scripts/odbc/catalog.json` (from `harvest.py`, the live schema)
and `scripts/odbc/enums.json` (from `enums.py`, the documented codes). Output:

    src/ajera/schemas/database/enums.py      one IntEnum per documented code column
    src/ajera/schemas/database/tables.py     one model per table
    src/ajera/schemas/database/views.py      one model per view
    src/ajera/schemas/database/functions.py  one row model per table-valued function
    src/ajera/schemas/database/__init__.py   re-exports and the source registries
    src/ajera/odbc/functions.py              one typed reader method per function

Run with `make odbc-generate`. Everything is derived, so a schema change is a
re-harvest and a re-run, never a hand edit.

Naming, so a field reads the same wherever its column appears:
- The table's column prefix is dropped (`gldControlAccountType` becomes
  `control_account_type`).
- A primary key named `Key` becomes `<entity>_key` (`AxProject.prjKey` is
  `project_key`), matching the REST models.
- A foreign key gains `_key` (`tProject` is `project_key`).
- Views and functions reuse a table column's field name; where two columns
  would collide in one model, both fall back to the full column name.
"""

import json
import keyword
import re
import subprocess
import sys
from collections import Counter
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from pydantic import BaseModel

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "scripts" / "odbc" / "catalog.json"
ENUMS = ROOT / "scripts" / "odbc" / "enums.json"
SCHEMAS = ROOT / "src" / "ajera" / "schemas" / "database"
READER = ROOT / "src" / "ajera" / "odbc" / "functions.py"

PY_TYPES = {
    "int": "int",
    "smallint": "int",
    "tinyint": "int",
    "bigint": "int",
    "bit": "bool",
    "decimal": "Decimal",
    "numeric": "Decimal",
    "money": "Decimal",
    "smallmoney": "Decimal",
    "float": "float",
    "real": "float",
    "varchar": "str",
    "nvarchar": "str",
    "char": "str",
    "nchar": "str",
    "text": "str",
    "ntext": "str",
    "xml": "str",
    "smalldatetime": "datetime",
    "datetime": "datetime",
    "datetime2": "datetime",
    "date": "date",
    "uniqueidentifier": "UUID",
    "timestamp": "bytes",
    "binary": "bytes",
    "varbinary": "bytes",
    "image": "bytes",
}
BLOB_TYPES = {"image", "varbinary", "binary"}

PARAMETER_TYPES = {
    "smalldatetime": "date | datetime",
    "datetime": "date | datetime",
    "bit": "bool",
    "tinyint": "int",
    "int": "int",
    "decimal": "Decimal | int",
    "varchar": "str",
}

# Columns kept out of `repr` so they never land in a log line or traceback:
# identity numbers, credentials, tokens, and banking details.
SENSITIVE = re.compile(
    r"SocialSecurity|Password|AccessToken|RefreshToken|Routing|BankAccountNumber"
    r"|^vecBankAccount$|^edAccount$|DateBorn|APIKey|Secret",
)

RESERVED = set(dir(BaseModel)) | {"custom_fields"}

# Views whose leading table key repeats across rows (a join fans it out), so it
# cannot serve as the view's row key. Found by `verify.py`.
NON_UNIQUE_VIEW_KEYS: set[str] = {
    "ClientInvoice",  # 11,145 rows over 10,823 ciKey values
}

HEADER = '''"""
{doc}

Generated by scripts/odbc/generate.py from scripts/odbc/catalog.json and
scripts/odbc/enums.json. Do not edit by hand; run `make odbc-generate`.
"""
'''


# =============================================================================
# Names
# =============================================================================


def snake(name: str) -> str:
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z\d])([A-Z])", r"\1_\2", name)
    return re.sub(r"_+", "_", name).strip("_").lower()


def prefix(column: str) -> str:
    match = re.match(r"[a-z]+", column)
    return match.group() if match else ""


def dominant_prefix(columns: Iterable[str]) -> str:
    counts = Counter(prefix(column) for column in columns)
    return counts.most_common(1)[0][0] if counts else ""


def entity(source: str) -> str:
    """`AxGLDetail` -> `GLDetail`; `IV_GLSummary_Receivable` -> `IVGLSummaryReceivable`."""
    stripped = source[2:] if re.match(r"Ax[A-Z]", source) else source
    return stripped.replace("_", "")


def identifier(name: str, fallback: str) -> str:
    if not name or name[0].isdigit():
        name = fallback
    if keyword.iskeyword(name) or name in RESERVED or name.startswith("model_"):
        name = f"{name}_"
    return name


def field_names(
    columns: list[dict[str, Any]],
    *,
    entity_snake: str,
    primary_key: list[str],
    foreign_keys: dict[str, Any],
    known: dict[str, str],
) -> dict[str, str]:
    """
    Name every column's field in one model, collision-free.

    Returns:
        dict[str, str]: Column name to field name.
    """
    names = [column["name"] for column in columns]
    lead = dominant_prefix(names)
    chosen: dict[str, str] = {}

    for name in names:
        if name in known:
            chosen[name] = known[name]
            continue
        rest = (
            name[len(lead) :]
            if prefix(name) == lead and len(name) > len(lead)
            else name
        )
        base = snake(rest)
        if rest == "Key" and name in primary_key:
            base = f"{entity_snake}_key"
        elif name in foreign_keys and not base.endswith("key"):
            base = f"{base}_key"
        chosen[name] = identifier(base, snake(name))

    # On a collision both columns fall back to their full names, except a
    # primary key, which keeps `<entity>_key` so it matches the REST models
    # (`AxProject.prjKey` stays `project_key`; `prjProject` yields).
    counts = Counter(chosen.values())
    for name, field in list(chosen.items()):
        if counts[field] > 1 and name not in primary_key:
            chosen[name] = identifier(snake(name), f"column_{snake(name)}")

    seen: Counter[str] = Counter()
    for name, field in list(chosen.items()):
        seen[field] += 1
        if seen[field] > 1:
            chosen[name] = f"{field}_{seen[field]}"
    return chosen


def member(label: str, code: int) -> str:
    name = re.sub(r"[^0-9a-zA-Z]+", "_", label).strip("_").lower()
    if not name:
        name = f"code_{code}".replace("-", "m")
    if name[0].isdigit():
        name = f"n_{name}"
    if (
        keyword.iskeyword(name)
        or name in {"name", "value", "mro"}
        or name.startswith("_")
    ):
        name = f"{name}_"
    return name


# =============================================================================
# Model rendering
# =============================================================================


class Module:
    """Collects one generated module's imports and body."""

    def __init__(self, doc: str) -> None:
        self.doc = doc
        self.types: set[str] = set()
        self.enums: set[str] = set()
        self.body: list[str] = []

    def render(self, base_names: str) -> str:
        imports = []
        if "date" in self.types or "datetime" in self.types:
            used = sorted({"date", "datetime"} & self.types)
            imports.append(f"from datetime import {', '.join(used)}")
        if "Decimal" in self.types:
            imports.append("from decimal import Decimal")
        if "UUID" in self.types:
            imports.append("from uuid import UUID")
        lines = [
            HEADER.format(doc=self.doc),
            *imports,
            "",
            "from pydantic import Field",
            "",
        ]
        lines.append(f"from ajera.schemas.database.base import {base_names}")
        if self.enums:
            lines.append(
                "from ajera.schemas.database.enums import (\n"
                + "".join(f"    {name},\n" for name in sorted(self.enums))
                + ")"
            )
        return "\n".join(lines) + "\n\n" + "\n".join(self.body)


def render_model(
    module: Module,
    *,
    class_name: str,
    doc: str,
    source_args: str,
    columns: list[dict[str, Any]],
    names: dict[str, str],
    enum_for: dict[str, str],
) -> None:
    lines = [
        "",
        f"class {class_name}(DatabaseRecord):",
        f'    """{doc}"""',
        "",
        f"    __source__ = Source({source_args})",
        "",
    ]
    for column in columns:
        sql_type = column["type"]
        py_type = PY_TYPES[sql_type]
        module.types.add(py_type)
        blob = sql_type in BLOB_TYPES
        nullable = column["nullable"] or blob

        enum = enum_for.get(column["name"]) if py_type == "int" else None
        arguments = [f'alias="{column["name"]}"']
        if enum:
            module.enums.add(enum)
            annotation = f"{enum} | int"
            arguments.append('union_mode="left_to_right"')
        else:
            annotation = py_type
        if SENSITIVE.search(column["name"]):
            arguments.append("repr=False")
        if nullable:
            annotation += " | None"
            arguments.insert(0, "None")
        lines.append(
            f"    {names[column['name']]}: {annotation} = Field({', '.join(arguments)})"
        )
    module.body.extend(lines)
    module.body.append("")


def source_literal(**values: Any) -> str:
    parts = [f'kind="{values["kind"]}"', f'name="{values["name"]}"']
    if values.get("primary_key"):
        parts.append(f"primary_key={tuple(values['primary_key'])!r}")
    if values.get("foreign_keys"):
        pairs = ", ".join(
            f'"{column}": ("{table}", "{target}")'
            for column, (table, target) in sorted(values["foreign_keys"].items())
        )
        parts.append(f"foreign_keys={{{pairs}}}")
    if values.get("blobs"):
        parts.append(f"blobs={tuple(values['blobs'])!r}")
    if values.get("parameters"):
        parts.append(f"parameters={tuple(values['parameters'])!r}")
    return ", ".join(parts)


# =============================================================================
# Generation
# =============================================================================


def main() -> None:
    catalog = json.loads(CATALOG.read_text())
    documented = json.loads(ENUMS.read_text())

    # -- enums ------------------------------------------------------------
    enum_for: dict[str, str] = {}
    enum_lines: list[str] = []
    used_enum_names: set[str] = set()
    for column, spec in sorted(
        documented.items(), key=lambda item: (item[1]["table"], item[0])
    ):
        table = catalog["tables"].get(spec["table"])
        if table is None:
            continue
        sql_type = next(
            (c["type"] for c in table["columns"] if c["name"] == column), None
        )
        if sql_type is None or PY_TYPES.get(sql_type) != "int":
            continue
        name = entity(spec["table"]) + column[len(prefix(column)) :]
        while name in used_enum_names:
            name += "Code"
        used_enum_names.add(name)
        enum_for[column] = name

        note = (
            " The export truncates long lists, so codes past the last one may be missing."
            if spec["truncated"]
            else ""
        )
        enum_lines += [
            "",
            f"class {name}(IntEnum):",
            f'    """`{spec["table"]}.{column}` codes, as Ajera documents them.{note}"""',
            "",
        ]
        members: set[str] = set()
        for code, label in sorted(spec["codes"].items(), key=lambda item: int(item[0])):
            member_name = member(label, int(code))
            if member_name in members:
                member_name = f"{member_name}_{code}".replace("-", "m")
            members.add(member_name)
            enum_lines.append(f"    {member_name} = {code}")
        enum_lines.append("")

    (SCHEMAS / "enums.py").write_text(
        HEADER.format(
            doc="Documented code values for the Ajera database's integer code columns.\n\n"
            "Each field that holds one of these codes is typed `<Enum> | int`: a documented\n"
            "code validates to its member, and an undocumented one stays a plain int\n"
            "rather than failing the read."
        )
        + "\nfrom enum import IntEnum\n\n"
        + "\n".join(enum_lines)
    )

    # -- tables -----------------------------------------------------------
    known: dict[str, str] = {}
    registry: dict[str, list[tuple[str, str]]] = {
        "tables": [],
        "views": [],
        "functions": [],
    }
    tables = Module("One model per Ajera database table.")
    for name, table in catalog["tables"].items():
        stem = entity(name)
        names = field_names(
            table["columns"],
            entity_snake=snake(stem),
            primary_key=table.get("primary_key", []),
            foreign_keys=table.get("foreign_keys", {}),
            known={},
        )
        known.update(names)
        class_name = f"{stem}Record"
        registry["tables"].append((name, class_name))
        key = table.get("primary_key", [])
        doc = f"A row of `{name}`" + (
            f", keyed by `{', '.join(key)}`." if key else ", which has no primary key."
        )
        render_model(
            tables,
            class_name=class_name,
            doc=doc,
            source_args=source_literal(
                kind="table",
                name=name,
                primary_key=key,
                foreign_keys=table.get("foreign_keys", {}),
                blobs=[c["name"] for c in table["columns"] if c["type"] in BLOB_TYPES],
            ),
            columns=table["columns"],
            names=names,
            enum_for=enum_for,
        )

    # -- views ------------------------------------------------------------
    # A view that leads with a table's key is one row per row of that table,
    # so the key pages it and finds rows in it like a primary key would.
    table_keys = {
        table["primary_key"][0]
        for table in catalog["tables"].values()
        if len(table.get("primary_key", [])) == 1
    }
    views = Module("One model per Ajera database view.")
    for name, view in catalog["views"].items():
        lead = view["columns"][0]["name"] if view["columns"] else ""
        view_key = (
            [lead] if lead in table_keys and name not in NON_UNIQUE_VIEW_KEYS else []
        )
        names = field_names(
            view["columns"],
            entity_snake=snake(entity(name)),
            primary_key=[],
            foreign_keys={},
            known=known,
        )
        class_name = f"{entity(name)}View"
        registry["views"].append((name, class_name))
        render_model(
            views,
            class_name=class_name,
            doc=f"A row of the `{name}` view"
            + (f", one per `{view_key[0]}`." if view_key else "."),
            source_args=source_literal(
                kind="view",
                name=name,
                primary_key=view_key,
                blobs=[c["name"] for c in view["columns"] if c["type"] in BLOB_TYPES],
            ),
            columns=view["columns"],
            names=names,
            enum_for=enum_for,
        )

    # -- functions --------------------------------------------------------
    functions = Module("One row model per Ajera table-valued function.")
    methods: list[str] = []
    method_types: set[str] = set()
    for name, function in catalog["functions"].items():
        stem = entity(name)
        class_stem = stem if not stem[0].isdigit() else name
        class_name = f"{class_stem}Row"
        names = field_names(
            function["columns"],
            entity_snake=snake(stem),
            primary_key=[],
            foreign_keys={},
            known=known,
        )
        registry["functions"].append((name, class_name))
        parameters = [p["name"] for p in function["parameters"]]
        signature = ", ".join(f"@{p}" for p in parameters)
        render_model(
            functions,
            class_name=class_name,
            doc=f"A row returned by `{name}({signature})`.",
            source_args=source_literal(
                kind="function",
                name=name,
                parameters=parameters,
                blobs=[
                    c["name"] for c in function["columns"] if c["type"] in BLOB_TYPES
                ],
            ),
            columns=function["columns"],
            names=names,
            enum_for=enum_for,
        )

        arguments = []
        for parameter in function["parameters"]:
            raw = re.sub(r"^p(?=[A-Z])", "", parameter["name"])
            arg = identifier(snake(raw), f"arg_{snake(raw)}")
            annotation = PARAMETER_TYPES[parameter["type"]]
            method_types.update(re.findall(r"\b(date|datetime|Decimal)\b", annotation))
            arguments.append((arg, annotation))
        method = snake(class_stem)
        methods += [
            "",
            f"    def {method}(",
            "        self,",
            *(f"        {arg}: {annotation} | None," for arg, annotation in arguments),
            "        *,",
            "        where: Where | None = None,",
            "        order_by: Sequence[str] | None = None,",
            "        limit: int | None = None,",
            "        offset: int | None = None,",
            f"    ) -> list[{class_name}]:",
            '        """',
            f"        Call `{name}({signature})`.",
            "",
            "        Returns:",
            f"            list[{class_name}]: The function's rows.",
            '        """',
            "        return self.call(",
            f"            {class_name},",
            *(f"            {arg}," for arg, _ in arguments),
            "            where=where,",
            "            order_by=order_by,",
            "            limit=limit,",
            "            offset=offset,",
            "        )",
        ]

    (SCHEMAS / "tables.py").write_text(tables.render("DatabaseRecord, Source"))
    (SCHEMAS / "views.py").write_text(views.render("DatabaseRecord, Source"))
    (SCHEMAS / "functions.py").write_text(functions.render("DatabaseRecord, Source"))

    # -- package re-exports and registries ---------------------------------
    enum_names = sorted(enum_for.values())
    exports = sorted(
        [
            "DatabaseRecord",
            "Source",
            "SourceKind",
            "TABLES",
            "VIEWS",
            "FUNCTIONS",
            "SOURCES",
        ]
        + enum_names
        + [cls for group in registry.values() for _, cls in group]
    )

    def block(module: str, names: list[str]) -> str:
        return (
            f"from ajera.schemas.database.{module} import (\n"
            + "".join(f"    {n},\n" for n in names)
            + ")\n"
        )

    def mapping(label: str, group: str) -> str:
        return (
            f"{label}: dict[str, type[DatabaseRecord]] = {{\n"
            + "".join(f'    "{name}": {cls},\n' for name, cls in registry[group])
            + "}\n"
        )

    init = (
        HEADER.format(
            doc="Models for every table, view, and table-valued function in the Ajera database.\n\n"
            "Read them through `ajera.odbc.AjeraOdbc`. The registries map each database\n"
            "object's own name to its model."
        )
        + "\n"
        + "from ajera.schemas.database.base import DatabaseRecord, Source, SourceKind\n"
        + block("enums", enum_names)
        + block("functions", [cls for _, cls in registry["functions"]])
        + block("tables", [cls for _, cls in registry["tables"]])
        + block("views", [cls for _, cls in registry["views"]])
        + "\n"
        + mapping("TABLES", "tables")
        + "\n"
        + mapping("VIEWS", "views")
        + "\n"
        + mapping("FUNCTIONS", "functions")
        + "\nSOURCES: dict[str, type[DatabaseRecord]] = {**TABLES, **VIEWS, **FUNCTIONS}\n\n"
        + "__all__ = [\n"
        + "".join(f'    "{name}",\n' for name in exports)
        + "]\n"
    )
    (SCHEMAS / "__init__.py").write_text(init)

    # -- typed function reads ------------------------------------------------
    datetime_imports = sorted({"date", "datetime"} & method_types)
    reader = (
        HEADER.format(
            doc="Typed calls to the Ajera database's table-valued functions.\n\n"
            "`AjeraOdbc` inherits these; each one forwards to `AjeraOdbc.call` with the\n"
            "function's row model and arguments in declaration order."
        )
        + "\nfrom collections.abc import Sequence\n"
        + (
            f"from datetime import {', '.join(datetime_imports)}\n"
            if datetime_imports
            else ""
        )
        + ("from decimal import Decimal\n" if "Decimal" in method_types else "")
        + "\n"
        + "from ajera.odbc.queries.select import Where\n"
        + "from ajera.schemas.database.base import DatabaseRecord\n"
        + block("functions", sorted(cls for _, cls in registry["functions"]))
        + "\n\nclass FunctionReads:\n"
        + '    """The database\'s table-valued functions, one typed method each."""\n\n'
        + "    def call[T: DatabaseRecord](\n"
        + "        self,\n"
        + "        model: type[T],\n"
        + "        *arguments: object,\n"
        + "        where: Where | None = None,\n"
        + "        order_by: Sequence[str] | None = None,\n"
        + "        limit: int | None = None,\n"
        + "        offset: int | None = None,\n"
        + "    ) -> list[T]:\n"
        + '        """\n'
        + "        Call a table-valued function and parse its rows.\n\n"
        + "        Returns:\n"
        + "            list[T]: The function's rows.\n"
        + '        """\n'
        + "        raise NotImplementedError\n"
        + "\n".join(methods)
        + "\n"
    )
    READER.write_text(reader)

    outputs = [str(path) for path in (*SCHEMAS.glob("*.py"), READER)]
    subprocess.run(["ruff", "check", "--fix", "--quiet", *outputs], check=False)
    subprocess.run(["ruff", "format", "--quiet", *outputs], check=True)
    print(
        f"{len(enum_for)} enums, {len(registry['tables'])} tables, "
        f"{len(registry['views'])} views, {len(registry['functions'])} functions"
    )
    sensitive = sorted(
        f"{name}.{c['name']}"
        for group in ("tables", "views")
        for name, source in catalog[group].items()
        for c in source["columns"]
        if SENSITIVE.search(c["name"])
    )
    print(
        f"repr=False on {len(sensitive)} columns: {', '.join(sensitive)}",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
