def main() -> None:
    catalog = json.loads(CATALOG.read_text())
    documented = json.loads(ENUMS.read_text())
    sources = {name for group in catalog.values() for name in group}
    unknown = sorted((set(NOTES) | set(SOURCE_NOTES) | set(VARYING)) - sources)
    unexplained = sorted(
        name
        for group in catalog.values()
        for name, source in group.items()
        if (source.get("repeated_key") or name in NON_UNIQUE_VIEW_KEYS)
        and name not in SOURCE_NOTES
    )
    if unexplained:
        raise SystemExit(
            "notes.py: say in SOURCE_NOTES what a row is for the sources whose "
            f"leading key repeats: {', '.join(unexplained)}"
        )
    if unknown:
        raise SystemExit(f"notes.py: no source named {', '.join(unknown)}")

    # -- enums ------------------------------------------------------------
    enum_for: dict[str, str] = {}
    enum_lines: list[str] = []
    enum_labels: dict[str, dict[int, str]] = {}
    used_enum_names: set[str] = set()
    for column, spec in sorted(
        documented.items(), key=lambda item: (item[1]["table"], item[0])
    ):
        table = catalog["tables"].get(spec["table"])
        if table is None:
            continue
        sql_type = next(
            (c["type"] for c in table["columns"] if c["name"] == column), None
        )
        if sql_type is None or PY_TYPES.get(sql_type) != "int":
            continue
        name = entity(spec["table"]) + column[len(prefix(column)) :]
        while name in used_enum_names:
            name += "Code"
        used_enum_names.add(name)
        enum_for[column] = name

        note = (
            " The export truncates long lists, so codes past the last one may be missing."
            if spec["truncated"]
            else ""
        )
        enum_lines += [
            "",
            f"class {name}(Code):",
            f'    """`{spec["table"]}.{column}` codes, as Ajera documents them.{note}"""',
            "",
        ]
        members: set[str] = set()
        enum_labels[name] = {}
        for code, label in sorted(spec["codes"].items(), key=lambda item: int(item[0])):
            member_name = member(label, int(code))
            if member_name in members:
                member_name = f"{member_name}_{code}".replace("-", "m")
            members.add(member_name)
            enum_lines.append(f"    {member_name} = {code}")
            enum_labels[name][int(code)] = label
        enum_lines.append("")

    labels = "".join(
        f"    {name}: {{{', '.join(f'{code}: {label!r}' for code, label in codes.items())}}},\n"
        for name, codes in enum_labels.items()
    )
    (SCHEMAS / "enums.py").write_text(
        HEADER.format(
            doc="Documented code values for the Ajera database's integer code columns.\n\n"
            "Each field that holds one of these codes is typed `<Enum> | int`: a documented\n"
            "code validates to its member, and an undocumented one stays a plain int\n"
            "rather than failing the read. Each member's `label` is Deltek's own text for\n"
            "the code."
        )
        + "\nfrom enum import IntEnum\n\n"
        + "\nclass Code(IntEnum):\n"
        + '    """A documented Ajera code, which knows Deltek\'s text for itself."""\n\n'
        + "    @property\n"
        + "    def label(self) -> str:\n"
        + '        """Deltek\'s documented text for the code (`"Write Off"`)."""\n'
        + "        return CODE_LABELS[type(self)][self.value]\n\n"
        + "\n".join(enum_lines)
        + "\n\n# Deltek's documented text for every code, by enum. The member names above are\n"
        + "# derived from these and lose their spacing and case.\n"
        + "CODE_LABELS: dict[type[Code], dict[int, str]] = {\n"
        + labels
        + "}\n"
    )

    # -- tables -----------------------------------------------------------
    known: dict[str, str] = {}
    registry: dict[str, list[tuple[str, str]]] = {
        "tables": [],
        "views": [],
        "functions": [],
    }
    tables = Module("One model per Ajera database table.")
    for name, table in catalog["tables"].items():
        stem = entity(name)
        names = field_names(
            table["columns"],
            entity_snake=snake(stem),
            primary_key=table.get("primary_key", []),
            foreign_keys=table.get("foreign_keys", {}),
            known={},
        )
        known.update(names)
        class_name = f"{stem}Record"
        registry["tables"].append((name, class_name))
        key = table.get("primary_key", [])
        doc = f"A row of `{name}`" + (
            f", keyed by `{', '.join(key)}`." if key else ", which has no primary key."
        )
        render_model(
            tables,
            class_name=class_name,
            doc=doc,
            source_args=source_literal(
                kind="table",
                name=name,
                primary_key=key,
                foreign_keys=table.get("foreign_keys", {}),
                blobs=[c["name"] for c in table["columns"] if c["type"] in BLOB_TYPES],
                **markers(name, table["columns"]),
            ),
            columns=table["columns"],
            names=names,
            enum_for=enum_for,
            notes=column_notes(name, table),
        )

    # -- views ------------------------------------------------------------
    # A view that leads with a table's key is one row per row of that table,
    # so the key pages it and finds rows in it like a primary key would.
    table_keys = {
        table["primary_key"][0]
        for table in catalog["tables"].values()
        if len(table.get("primary_key", [])) == 1
    }
    views = Module("One model per Ajera database view.")
    for name, view in catalog["views"].items():
        lead = view["columns"][0]["name"] if view["columns"] else ""
        view_key = (
            [lead] if lead in table_keys and name not in NON_UNIQUE_VIEW_KEYS else []
        )
        repeated = lead if name in NON_UNIQUE_VIEW_KEYS else None
        names = field_names(
            view["columns"],
            entity_snake=snake(entity(name)),
            primary_key=[],
            foreign_keys={},
            known=known,
        )
        class_name = f"{entity(name)}View"
        registry["views"].append((name, class_name))
        render_model(
            views,
            class_name=class_name,
            doc=f"A row of the `{name}` view"
            + (f", one per `{view_key[0]}`." if view_key else "."),
            source_args=source_literal(
                kind="view",
                name=name,
                primary_key=view_key,
                blobs=[c["name"] for c in view["columns"] if c["type"] in BLOB_TYPES],
                **markers(name, view["columns"]),
                repeated_key=repeated,
                note=SOURCE_NOTES.get(name),
            ),
            columns=view["columns"],
            names=names,
            enum_for=enum_for,
            notes=column_notes(name, view, repeated, names),
        )

    # -- functions --------------------------------------------------------
    functions = Module("One row model per Ajera table-valued function.")
    methods: list[str] = []
    method_types: set[str] = set()
    for name, function in catalog["functions"].items():
        stem = entity(name)
        class_stem = stem if not stem[0].isdigit() else name
        class_name = f"{class_stem}Row"
        names = field_names(
            function["columns"],
            entity_snake=snake(stem),
            primary_key=[],
            foreign_keys={},
            known=known,
        )
        registry["functions"].append((name, class_name))
        parameters = [p["name"] for p in function["parameters"]]
        signature = ", ".join(f"@{p}" for p in parameters)
        # From `probe.py`, in call order: the parameters the function does not
        # apply, what to filter on instead, and those it ignores only under
        # some codes.
        ignored = [p for p in parameters if p in function.get("ignored_parameters", ())]
        filters = function.get("parameter_filters", {})
        notes = function.get("parameter_notes", {})
        conditional = function.get("ignored_when", {})
        when = {
            p: {code: tuple(values) for code, values in conditional[p].items()}
            for p in parameters
            if p in conditional
        }
        render_model(
            functions,
            class_name=class_name,
            doc=f"A row returned by `{name}({signature})`.",
            source_args=source_literal(
                kind="function",
                name=name,
                parameters=parameters,
                parameter_types=[declaration(p) for p in function["parameters"]],
                ignored_parameters=ignored,
                parameter_filters={p: filters[p] for p in ignored if p in filters},
                parameter_notes={p: notes[p] for p in ignored if p in notes},
                ignored_when=when,
                blobs=[
                    c["name"] for c in function["columns"] if c["type"] in BLOB_TYPES
                ],
                **markers(name, function["columns"]),
                row_key=function.get("row_key", []),
                repeated_key=function.get("repeated_key"),
                note=SOURCE_NOTES.get(name),
            ),
            columns=function["columns"],
            names=names,
            enum_for=enum_for,
            notes=column_notes(name, function, function.get("repeated_key"), names),
        )

        arguments = []
        for parameter in function["parameters"]:
            raw = re.sub(r"^p(?=[A-Z])", "", parameter["name"])
            arg = identifier(snake(raw), f"arg_{snake(raw)}")
            annotation = PARAMETER_TYPES[parameter["type"]]
            method_types.update(re.findall(r"\b(date|datetime|Decimal)\b", annotation))
            arguments.append((arg, annotation))
        method = snake(class_stem)
        arg = {p: arguments[parameters.index(p)][0] for p in parameters}
        caveats = []
        if ignored:
            caveats.append(
                ignored_caveat(
                    [arg[p] for p in ignored],
                    fields=[names[filters[p]] for p in ignored if p in filters],
                    notes=[notes[p] for p in ignored if p in notes],
                )
            )
        for conditions in dict.fromkeys(repr(c) for c in when.values()):
            held = [p for p in when if repr(when[p]) == conditions]
            caveats.append(
                conditional_caveat([arg[p] for p in held], when[held[0]], arg)
            )
        caveat = [
            line
            for text in caveats
            for line in [
                "",
                *textwrap.wrap(
                    text, width=79, initial_indent=" " * 8, subsequent_indent=" " * 8
                ),
            ]
        ]
        methods += [
            "",
            f"    def {method}(",
            "        self,",
            *(f"        {arg}: {annotation} | None," for arg, annotation in arguments),
            "        *,",
            "        where: Where | None = None,",
            "        order_by: Sequence[str] | None = None,",
            "        limit: int | None = None,",
            "        offset: int | None = None,",
            "        timeout: int | None = None,",
            f"    ) -> list[{class_name}]:",
            '        """',
            f"        Call `{name}({signature})`.",
            *caveat,
            "",
            "        Returns:",
            f"            list[{class_name}]: The function's rows.",
            '        """',
            "        return self.call(",
            f"            {class_name},",
            *(f"            {arg}," for arg, _ in arguments),
            "            where=where,",
            "            order_by=order_by,",
            "            limit=limit,",
            "            offset=offset,",
            "            timeout=timeout,",
            "        )",
        ]

    (SCHEMAS / "tables.py").write_text(tables.render("DatabaseRecord, Source"))
    (SCHEMAS / "views.py").write_text(views.render("DatabaseRecord, Source"))
    (SCHEMAS / "functions.py").write_text(functions.render("DatabaseRecord, Source"))

    # -- package re-exports and registries ---------------------------------
    sensitive_columns = sorted(
        {
            c["name"]
            for group in ("tables", "views", "functions")
            for source in catalog[group].values()
            for c in source["columns"]
            if SENSITIVE.search(c["name"])
        }
    )
    enum_names = sorted(enum_for.values())
    exports = sorted(
        [
            "CODE_LABELS",
            "Code",
            "DatabaseRecord",
            "FieldSchema",
            "SENSITIVE_COLUMNS",
            "Source",
            "SourceKind",
            "SourceSchema",
            "describe",
            "TABLES",
            "VIEWS",
            "FUNCTIONS",
            "SOURCES",
        ]
        + enum_names
        + [cls for group in registry.values() for _, cls in group]
    )

    def block(module: str, names: list[str]) -> str:
        return (
            f"from ajera.schemas.database.{module} import (\n"
            + "".join(f"    {n},\n" for n in names)
            + ")\n"
        )

    def mapping(label: str, group: str) -> str:
        return (
            f"{label}: dict[str, type[DatabaseRecord]] = {{\n"
            + "".join(f'    "{name}": {cls},\n' for name, cls in registry[group])
            + "}\n"
        )

    init = (
        HEADER.format(
            doc="Models for every table, view, and table-valued function in the Ajera database.\n\n"
            "Read them through `ajera.odbc.AjeraOdbc`. The registries map each database\n"
            "object's own name to its model."
        )
        + "\n"
        + "from ajera.schemas.database.base import DatabaseRecord, Source, SourceKind\n"
        + "from ajera.schemas.database.describe import FieldSchema, SourceSchema, describe\n"
        + block("enums", ["CODE_LABELS", "Code", *enum_names])
        + block("functions", [cls for _, cls in registry["functions"]])
        + block("tables", [cls for _, cls in registry["tables"]])
        + block("views", [cls for _, cls in registry["views"]])
        + "\n"
        + mapping("TABLES", "tables")
        + "\n"
        + mapping("VIEWS", "views")
        + "\n"
        + mapping("FUNCTIONS", "functions")
        + "\nSOURCES: dict[str, type[DatabaseRecord]] = {**TABLES, **VIEWS, **FUNCTIONS}\n\n"
        + "# Every column name the generator classifies as sensitive, across all sources:\n"
        + "# identity numbers, credentials, tokens, and banking details.\n"
        + "SENSITIVE_COLUMNS: frozenset[str] = frozenset(\n    {\n"
        + "".join(f'        "{name}",\n' for name in sensitive_columns)
        + "    }\n)\n\n"
        + "__all__ = [\n"
        + "".join(f'    "{name}",\n' for name in exports)
        + "]\n"
    )
    (SCHEMAS / "__init__.py").write_text(init)

    # -- typed function reads ------------------------------------------------
    datetime_imports = sorted({"date", "datetime"} & method_types)
    reader = (
        HEADER.format(
            doc="Typed calls to the Ajera database's table-valued functions.\n\n"
            "`AjeraOdbc` inherits these; each one forwards to `AjeraOdbc.call` with the\n"
            "function's row model and arguments in declaration order."
        )
        + "\nfrom collections.abc import Sequence\n"
        + (
            f"from datetime import {', '.join(datetime_imports)}\n"
            if datetime_imports
            else ""
        )
        + ("from decimal import Decimal\n" if "Decimal" in method_types else "")
        + "\n"
        + "from ajera.odbc.queries.select import Where\n"
        + "from ajera.schemas.database.base import DatabaseRecord\n"
        + block("functions", sorted(cls for _, cls in registry["functions"]))
        + "\n\nclass FunctionReads:\n"
        + '    """The database\'s table-valued functions, one typed method each."""\n\n'
        + "    def call[T: DatabaseRecord](\n"
        + "        self,\n"
        + "        model: type[T],\n"
        + "        *arguments: object,\n"
        + "        where: Where | None = None,\n"
        + "        order_by: Sequence[str] | None = None,\n"
        + "        limit: int | None = None,\n"
        + "        offset: int | None = None,\n"
        + "        timeout: int | None = None,\n"
        + "    ) -> list[T]:\n"
        + '        """\n'
        + "        Call a table-valued function and parse its rows.\n\n"
        + "        Returns:\n"
        + "            list[T]: The function's rows.\n"
        + '        """\n'
        + "        raise NotImplementedError\n"
        + "\n".join(methods)
        + "\n"
    )
    READER.write_text(reader)

    outputs = [str(path) for path in (*SCHEMAS.glob("*.py"), READER)]
    subprocess.run(["ruff", "check", "--fix", "--quiet", *outputs], check=False)
    subprocess.run(["ruff", "format", "--quiet", *outputs], check=True)
    print(
        f"{len(enum_for)} enums, {len(registry['tables'])} tables, "
        f"{len(registry['views'])} views, {len(registry['functions'])} functions"
    )
    sensitive = sorted(
        f"{name}.{c['name']}"
        for group in ("tables", "views", "functions")
        for name, source in catalog[group].items()
        for c in source["columns"]
        if SENSITIVE.search(c["name"])
    )
    print(
        f"repr=False on {len(sensitive)} columns: {', '.join(sensitive)}",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
